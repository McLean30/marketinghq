/* ---------- Review ---------- */
function renderJob(id) {
  const job = S.getJob(id);
  if (!job) return notFound();
  const { copy, graphic } = S.jobTasks(job);
  const st = S.jobStatus(job);
  const canApprove = st === 'ready_for_review' || st === 'needs_reapproval';
  const cv = copy.versions.length, gv = graphic.versions.length;
  const vis = S.visualLabel(job).toLowerCase();
  let approveText;
  if (st === 'needs_render') approveText = 'Approval opens once the video is rendered. Open the video editor to render version 1.';
  else if (st === 'approved') approveText = `Approved caption v${job.approval.copyVersion} with ${vis} v${job.approval.graphicVersion}. On your private calendar for ${fmtDate(job.targetDate, { weekday: 'long', day: 'numeric', month: 'long' })}. Approval doesn’t publish or schedule anything.`;
  else if (st === 'needs_reapproval') approveText = `Approved earlier as caption v${job.approval.copyVersion} + ${vis} v${job.approval.graphicVersion}. The pair has changed since, so it needs fresh approval.`;
  else if (canApprove) approveText = `Approving caption v${cv} with ${vis} v${gv} puts this post on the private calendar. Nothing is published or scheduled: that’s a separate step.`;
  else approveText = 'Approval opens when both the caption and graphic are ready.';
  return `
  <nav class="crumbs"><a href="#/">← HQ</a>${job.sample ? ` · <a href="#/agent/analyst">Vantage’s analysis</a>` : ''}</nav>
  ${job.sample ? '<p class="sample-banner" data-testid="sample-banner"><strong>Sample post.</strong> Made-up content and figures for trying the Marketing Analyst. It was never published anywhere and isn’t one of your posts.</p>' : ''}
  <div id="sync-slot">${syncNotice(job.id)}</div>
  <header class="job-head">
    <div class="job-head-top"><span class="plat plat-${platSlug(job.platform)}">${job.platform}</span><span class="job-date">${fmtDate(job.targetDate, { weekday: 'long', day: 'numeric', month: 'long', year: 'numeric' })}</span>${pill(st)}${pubPill(job)}</div>
    <h1>${esc(jobTitle(job))}</h1>
    ${job.planId ? `<p class="plan-link" data-testid="plan-link">Part of <a href="#/week/${job.planId}">${esc(PL.fmtWeek(S.getPlan(job.planId)?.weekStart || job.targetDate))}</a> · ${esc(job.planDay.dayName)} · ${esc(job.platform)}. Audience: ${esc(job.planDay.audience)}.</p>` : ''}
    <details class="brief-detail" data-key="brief-${job.id}"><summary>Your brief</summary><p>${esc(job.brief)}</p></details>
    <p class="profile-chip" data-testid="job-profile">Business profile: ${S.jobProfileRef(job) ? `<a href="#/profile" data-profile-link>${esc(S.jobProfileRef(job).id)}</a>${S.jobProfileRef(job).id !== S.currentProfile()?.id ? ` (current: ${esc(S.currentProfile()?.id || '')})` : ' (current)'}` : 'none recorded: this post was created before the business profile'}</p>
  </header>
  ${profileImpactNotice(job)}
  <div class="review-grid">
    ${assetPanel(job, copy)}
    ${assetPanel(job, graphic)}
  </div>
  ${reviewPanel(job)}
  <div class="approve-bar" data-status="${st}">
    <p>${esc(approveText)}</p>
    ${st === 'approved' ? `<a class="btn" href="#/calendar">View calendar</a>` : `<button class="btn btn-primary" data-approve="${job.id}" ${canApprove ? '' : 'disabled'}>${st === 'needs_reapproval' ? 'Approve changed pair' : 'Approve pair'}</button>`}
  </div>
  ${publishPanel(job)}
  ${resultsPanel(job)}`;
}

