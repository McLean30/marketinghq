/** Markup for any graphic version: inline SVG for simulated, a rendered PNG for Photo layout. */
function graphicMarkup(task, v, { title } = {}) {
  if (v.content.mode !== 'photo') return renderGraphic(v.content, title ? { title } : undefined);
  const r = P.renderedVersion(`${task.id}:${v.n}`, v.content, () => render());
  if (!r) return `<span class="photo-pending" role="img" aria-label="Rendering graphic v${v.n}">Rendering…</span>`;
  if (r.error) return `<span class="photo-pending error" role="img" aria-label="Graphic v${v.n} could not be rendered">Couldn’t render v${v.n}: ${esc(r.error)}</span>`;
  const warn = r.missing?.length ? `<span class="asset-warn">Missing from this browser: ${r.missing.join(' and ')}</span>` : '';
  return `<img src="${r.url}" width="${P.W}" height="${P.H}" alt="${esc(title || `Graphic v${v.n}`)}: ${esc(v.content.headline)}" data-photo-version="${v.n}">${warn}`;
}

// "claude-sonnet-5-5" -> "Claude Sonnet 5.5"
function modelName(m) {
  const match = /^claude-([a-z]+)-(\d+(?:-\d+)?)/.exec(m || '');
  if (!match) return m || 'Claude';
  return `Claude ${match[1][0].toUpperCase()}${match[1].slice(1)} ${match[2].replace('-', '.')}`;
}
function sourceTag(v) {
  const src = v.source || (v.simulated ? 'demo' : 'human');
  if (src === 'anthropic') return `<span class="demo-tag ai" title="Generated by ${esc(v.model)} via the Anthropic API">AI-generated · ${esc(modelName(v.model))}</span>`;
  if (src === 'mock') return `<span class="demo-tag mock" title="Canned response from the test mock provider, not AI">Mock AI response (test mode)</span>`;
  if (src === 'human') return '<span class="demo-tag human">Edited by you</span>';
  return demoTag;
}
function quillModeNote() {
  const q = S.quill;
  if (!q.checked) return '';
  if (q.provider === 'anthropic') return `<p class="quill-mode live" data-testid="quill-mode">Quill writes captions with ${esc(modelName(q.model))} (live AI). Graphics are still simulated.</p>`;
  if (q.provider === 'mock') return '<p class="quill-mode mock" data-testid="quill-mode">Quill is using the mock provider (test mode). Captions are canned, not AI.</p>';
  return '<p class="quill-mode" data-testid="quill-mode">Quill is in demo mode: captions come from local templates. Add ANTHROPIC_API_KEY to the server to switch on live AI.</p>';
}

/* ---------- Routing ---------- */
function route() {
  const h = location.hash.replace(/^#/, '') || '/';
  const [, a, b] = h.split('/');
  const parts = h.split('/');
  if (a === 'job' && b && parts[3] === 'studio') return { view: 'studio', id: b, base: `#/job/${b}` };
  if (a === 'job' && b) return { view: 'job', id: b, agent: parts[3] === 'agent' ? parts[4] : null, base: `#/job/${b}` };
  if (a === 'calendar') return { view: 'calendar' };
  if (a === 'workspace') return { view: 'workspace' };
  if (a === 'week' && b) return { view: 'week', id: b };
  if (a === 'profile') return { view: 'profile' };
  if (a === 'agent' && b) return { view: 'hq', agent: b, base: '#/' };
  return { view: 'hq' };
}

